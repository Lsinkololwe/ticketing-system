package com.pml.identity.service;

import com.pml.identity.domain.model.User;
import com.pml.shared.constants.UserType;
import reactor.core.publisher.Flux;
import reactor.core.publisher.Mono;

import java.util.Set;

/**
 * Reads accounts and edits what an account may change about itself (ET-IDN-004).
 *
 * <p>An account is identified by its contacts, not by an email or a phone number stored on it: a
 * lookup by contact goes through {@code identity_contacts} by the contact's keyed hash. Contacts are
 * never written here - they are claimed by proving control of them - and status, suspension, deletion
 * and roles belong to {@link com.pml.identity.account.AccountService}, which this service delegates to
 * for roles so callers keep one facade.</p>
 */
public interface UserService {

    Mono<User> findById(String id);

    /** The account a token's {@code sub} belongs to. */
    Mono<User> findBySubject(String subject);

    Mono<User> findByUsername(String username);

    /** By the verified email contact; legacy accounts that still carry the address on the document are found too. */
    Mono<User> findByEmail(String email);

    /** By the verified WhatsApp contact; legacy accounts that still carry the number on the document are found too. */
    Mono<User> findByPhoneNumber(String phoneNumber);

    Flux<User> findAll();

    Flux<User> findByRole(UserType role);

    Mono<Boolean> existsByEmail(String email);

    Mono<Boolean> existsByUsername(String username);

    /**
     * Creates a platform staff user. Staff accounts exist only in the staff realm (password and a
     * second factor required at first sign-in) and always hold exactly one staff role: ADMIN,
     * SUPER_ADMIN, FINANCE or FINANCE_LEAD. Buyers and organizers are never created here; they come
     * into being by proving a contact.
     *
     * <p>The creation is a durable process: it either finishes or leaves nothing behind, and a request
     * repeated while it is still running returns the same account. A role that cannot be granted removes
     * the Keycloak user and the stored account again. A role that is not a staff role, or a number that
     * does not parse, is refused before anything is created. Who may call is decided by the caller of
     * this method; see {@link com.pml.identity.account.StaffRolePolicy}.</p>
     *
     * <p>The person's first password is generated by the system and returned, once, on the answer of the
     * call that created the account; see {@link com.pml.identity.account.StaffAccountPassword}.</p>
     *
     * @param phoneNumber optional mobile number of the staff member, normalised and stored
     */
    Mono<com.pml.identity.account.StaffAccountPassword> createStaffUser(String email, String firstName, String lastName,
                                                                        String phoneNumber, com.pml.shared.constants.UserType role,
                                                                        String actorId);

    /**
     * Replaces a staff member's password with a new one-time password, ends the sessions they hold and
     * returns the password once. Only for a super administrator, only for a staff account.
     */
    Mono<com.pml.identity.account.StaffAccountPassword> resetStaffTemporaryPassword(String userId, String actorId);

    /** Soft-deletes the account (status DELETED, Keycloak disabled, sessions ended); nothing is erased. */
    Mono<User> deleteUser(String id, String actorId);

    /** Names and display name only; null leaves a field alone. Contacts are not editable here. */
    Mono<User> updateProfile(String id, User profileData);

    Mono<User> addRole(String userId, UserType role, String addedBy);

    Mono<User> removeRole(String userId, UserType role, String removedBy);

    Mono<User> setRoles(String userId, Set<UserType> roles, String updatedBy);

    Mono<Set<UserType>> getRoles(String userId);
}
